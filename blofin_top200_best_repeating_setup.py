"""Read-only, second-stage ranking of ONE setup repeating >=3 times EVERY day.

Reuses the exact same 390-coin candle artifacts and causal historical TOP200
signals generated by original backtest. DOES NOT request exchange candles
again. Picks strategy using only first 4 days, then shows later 2+2 days
without tuning. Makes no LIVE changes.
"""
from __future__ import annotations
import itertools
import json
import statistics
from pathlib import Path

import blofin_top200_repeat_setup_research as original
import blofin_top200_parallel_runner as parallel

SOURCE_FUNC=original.compute_daily
CAPTURE={}


def intercept(byfam,cache,rule,exitid,days):
    CAPTURE["byfam"]=byfam
    CAPTURE["cache"]=cache
    CAPTURE["days"]=days
    return SOURCE_FUNC(byfam,cache,rule,exitid,days)


original.compute_daily=intercept
parallel.analyze()
original.compute_daily=SOURCE_FUNC
byfam=CAPTURE["byfam"]
cached=CAPTURE["cache"]

days=[(parallel.anchor().replace(hour=0)-original.timedelta(days=original.NUM_DAYS-i)).date().isoformat()
      for i in range(original.NUM_DAYS)]
train_days=days[:4]
validation_days=days[4:6]
test_days=days[6:8]
allrules=list(itertools.product(original.FAMILY,original.VOL_MULT,original.BODY_MIN,original.SIDES))

ranking=[]
frequent_configs=0
train_positive=0
for rule in allrules:
    for exitid,cfg in enumerate(original.EXIT_LIST):
        training=original.assess(SOURCE_FUNC(byfam,cached,rule,exitid,train_days))
        # Data explicitly require AT LEAST THREE FILLED (non-overlapping) trades
        # on each of first four complete UK days.
        if training["min_trades_in_day"]<3:
            continue
        frequent_configs+=1
        if training["avg_net_usdt_per_day"]>0:
            train_positive+=1
        ranking.append((rule,exitid,training))
# Only first four days decide ranking; do not rank by validation/holdout.
ranking.sort(key=lambda x:(
    x[2]["days_at_least_3pct"],
    x[2]["avg_net_usdt_per_day"],
    x[2]["min_day_net_usdt"]),reverse=True)

best=[]
for rule,idx,tr in ranking[:5]:
    valid=original.assess(SOURCE_FUNC(byfam,cached,rule,idx,validation_days))
    test=original.assess(SOURCE_FUNC(byfam,cached,rule,idx,test_days))
    tp,sl,hold=original.EXIT_LIST[idx]
    best.append({
        "family":rule[0],"volume_vs_median20_min":rule[1],
        "body_min_pct":rule[2],"direction":rule[3],
        "tp_pct":tp*100,"sl_pct":sl*100,"max_hold_minutes":hold*5,
        "training_four_days":tr,"validation_next_two_days":valid,
        "holdout_last_two_days":test,
        "min_3trades_all_8days":tr["min_trades_in_day"]>=3 and valid["min_trades_in_day"]>=3 and test["min_trades_in_day"]>=3,
        "average_net_across_eight_days_usdt":round((
            tr["total_net_usdt"]+valid["total_net_usdt"]+test["total_net_usdt"])/8,4),
        "days_at_least_3pct_eight":tr["days_at_least_3pct"]+valid["days_at_least_3pct"]+test["days_at_least_3pct"]
    })

report={
    "research_period_uk":days,
    "required": "Same single entry family/vol/body/direction/TP/SL/hold all days. Minimum 3 actual serial trades each day. Fees0.12%, adverse slippage0.10%. Capital reference20USDT.",
    "all_configurations":len(allrules)*len(original.EXIT_LIST),
    "frequent_in_each_of_first_4days":frequent_configs,
    "profitable_average_first_4days_given_frequency":train_positive,
    "top_five_by_training_only":best,
    "selection_warning":"Top 5 are selected only on training days; later validation and holdout are diagnostic and not used for selection. Only 8 days, future performance not guaranteed. Point-in-time 24h gainers among current eligible 390 symbols; ignores historic delistings, funding & real exchange spread. No LIVE changes."
}
out=Path("blofin_top200_best_repeating_setup_report.json")
out.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
print("BEST_REPEATING_SETUP_RESULT="+json.dumps(report,ensure_ascii=False,separators=(",",":")),flush=True)
